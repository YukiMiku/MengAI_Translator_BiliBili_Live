# -*- coding: utf-8 -*-
"""版本号的唯一来源。

改版本号只需要改这一个文件；窗口标题、自检输出、压缩包/文件夹命名都以它为准，
这样就不会再出现"压缩包是 0.7.3、内部还是 0.6"这种内外不一致的情况。

==========================================================================
版本号迭代规则（三段式 X.Y.Z）—— 由项目所有者声明
==========================================================================

  X（第一位，大版本）
      * 只在功能迭代把第二位推到 11 时进位：X = X + 1
      * 第一位一旦变化，第二位与第三位一律清零
      例：v1.10.0 --(再新增功能)--> v2.0.0

  Y（第二位，功能新增）
      * 每新增一个功能，Y = Y + 1
      * 功能迭代时，第三位一律清零（把上一轮的 bug 修复计数带过去没有意义）
      * Y 的取值范围是 0 ~ 10；到 10 为止，再 +1 就进位到第一位
      例：v1.0.0  --(新增功能)--> v1.1.0
          v1.3.7  --(新增功能)--> v1.4.0    ← 第三位清零
          v1.9.0  --(新增功能)--> v1.10.0
          v1.10.0 --(新增功能)--> v2.0.0    ← 进位，第二、三位清零

  Z（第三位，仅修 bug）
      * 只有"仅修复 bug"时才 Z = Z + 1
      * Z 可以无限累计，绝不向第二位进位
      * 遇到功能迭代（Y 变化）或大版本进位（X 变化）时，Z 归零
      例：v1.0.0 --(修 bug)--> v1.0.1 --> v1.0.2 --> ... --> v1.0.999

  记忆口诀：
      新功能动第二位、顺手把第三位清零；修 bug 只动第三位；
      第三位不顶位，第二位满 11 就进大版本，大版本一进全清零。

  完整演进示例：
      v1.0.0  首发
      v1.0.1  修了一个 bug
      v1.0.2  又修了一个 bug
      v1.1.0  新增功能（第三位清零）
      v1.2.0  再新增功能
      v1.2.1  修 bug
      v1.3.0  又新增功能（第三位再次清零）
      ...
      v1.10.0 第二位的最后一个可用值
      v2.0.0  第二位溢出 -> 进位，第二、三位清零

==========================================================================
发版流程
==========================================================================
    1. 按上面的规则修改下面的 APP_VERSION
    2. 把整个工程目录重命名为 f'{APP_NAME}-v{APP_VERSION}'
       （便携版例外：固定在 install.bat 所在目录下的 f'{APP_NAME}'，不带版本号，
         这样快捷方式才长期有效）
    3. 压缩成同名 zip
    4. 跑一次 python selfcheck.py，确认「内外版本号一致」
"""

# 工具名称（中文界面用）
APP_NAME = 'AI萌译酱'
# 工具名称（日语界面用）
APP_NAME_EN = 'AI-MengYiJiang'
APP_NAME_JA = '萌AIちゃん'

APP_VERSION = '1.4.3'

APP_TITLE = f'{APP_NAME} v{APP_VERSION}'
APP_TITLE_JA = f'{APP_NAME_JA} v{APP_VERSION}'


def app_title(lang='zh'):
    """按界面语言返回窗口标题。"""
    return APP_TITLE_JA if str(lang).lower().startswith('ja') else APP_TITLE
